from django.conf import settings
from django.db import models


class PushSubscription(models.Model):
    """
    Tenant-scoped Web Push subscription. The endpoint and keys are generated by
    the browser Push API; the private VAPID key never leaves the server.
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="push_subscriptions",
    )
    endpoint = models.URLField(max_length=600, unique=True)
    p256dh = models.CharField(max_length=200)
    auth = models.CharField(max_length=100)
    user_agent = models.CharField(max_length=300, blank=True, default="")
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)
    last_seen_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-last_seen_at", "-id"]

    def __str__(self):
        return f"{self.user_id} -> {self.endpoint[:48]}…"


class Notification(models.Model):
    class Category(models.TextChoices):
        NEW_ORDER = "NEW_ORDER", "New Order"
        KDS_READY = "KDS_READY", "KDS Dish Ready"
        RESERVATION = "RESERVATION", "Table Reservation"
        LOW_STOCK = "LOW_STOCK", "Low Stock Alert"
        BILLING = "BILLING", "Billing & Cashier"
        SYSTEM = "SYSTEM", "System Notice"

    class Severity(models.TextChoices):
        INFO = "INFO", "Info"
        SUCCESS = "SUCCESS", "Success"
        WARNING = "WARNING", "Warning"
        CRITICAL = "CRITICAL", "Critical"

    recipient = models.ForeignKey(
        "accounts.User",
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name="notifications",
    )
    branch = models.ForeignKey(
        "branches.Branch",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="notifications",
    )
    category = models.CharField(
        max_length=25,
        choices=Category.choices,
        default=Category.SYSTEM,
    )
    severity = models.CharField(
        max_length=20,
        choices=Severity.choices,
        default=Severity.INFO,
    )
    title = models.CharField(max_length=180)
    message = models.TextField(blank=True, default="")
    action_url = models.CharField(max_length=250, blank=True, default="/dashboard")
    is_read = models.BooleanField(default=False)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at", "-id"]

    def __str__(self):
        return f"[{self.category}] {self.title}"
